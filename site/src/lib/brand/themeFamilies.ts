export type ThemeFamily = keyof typeof THEME_FAMILIES

export const THEME_FAMILY_IDS = Object.keys(THEME_FAMILIES) as ThemeFamily[]

export const DEFAULT_THEME_FAMILY: ThemeFamily = "eris"

export const themeName = (family: ThemeFamily, scheme: ColorScheme) =>
  scheme === "dark" ? family : `${family}-light`

export const themeRules = () => {
  const rules: Record<string, Record<string, string>> = {}

  for (const family of THEME_FAMILY_IDS) {
    const definition: ThemeFamilyDefinition = THEME_FAMILIES[family]
    const style = { ...BASE_THEME_STYLE, ...definition.style }

    for (const scheme of COLOR_SCHEMES) {
      const selector = `[data-theme="${themeName(family, scheme)}"]`
      const fallback = family === DEFAULT_THEME_FAMILY && scheme === "dark"

      rules[fallback ? `:where(:root),${selector}` : selector] = {
        "color-scheme": scheme,
        ...Object.fromEntries(
          THEME_TOKENS.map(token => [
            `--color-${token}`,
            definition[scheme][token],
          ]),
        ),
        ...Object.fromEntries(
          Object.entries(style).map(([token, value]) => [`--${token}`, value]),
        ),
      }
    }
  }

  return rules
}
